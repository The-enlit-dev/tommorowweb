#!/usr/bin/env bash
# Concatenates supabase/pending/*.sql (in order) into one transaction: supabase/pending/APPLY_ALL.sql
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=supabase/pending/APPLY_ALL.sql
{
  echo "-- Tomorrow Web: all pending migrations in order, in ONE transaction (all or nothing)."
  echo "-- Paste into Supabase → SQL Editor → Run. Generated by scripts/bundle-pending.sh — do not edit."
  echo "begin;"
  for f in supabase/pending/2*.sql; do
    echo; echo "-- ════ $(basename "$f") ════"; cat "$f"
  done
  echo; echo "commit;"
  echo "select 'Tomorrow Web migrations applied' as result, (select count(*) from information_schema.tables where table_schema = 'public') as public_tables;"
} > "$OUT"
echo "wrote $OUT ($(wc -l < "$OUT") lines)"
