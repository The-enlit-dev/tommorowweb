// Generates thin Astro wrappers for portal routes: src/pages/portal/<route>/index.astro
// Usage: node scripts/portal-pages.mjs   (idempotent; edit the ROUTES table below)
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'

export const ROUTES = [
  // route, module file (src/portal/pages/X.tsx), export, title
  ['login', 'Auth', 'Login', 'Sign in'],
  ['password', 'Auth', 'Password', 'Password'],
  ['', 'Home', 'Dashboard', 'Dashboard'],
  ['account', 'Home', 'Account', 'Account'],
  ['team', 'Home', 'Team', 'Team'],
  ['settings', 'Home', 'Settings', 'Business settings'],
  ['admin', 'Admin', 'AdminOverview', 'Admin'],
  ['admin/clients', 'Admin', 'Clients', 'Clients'],
  ['admin/business', 'Admin', 'BusinessDetail', 'Business'],
  ['admin/audit', 'Admin', 'Audit', 'Audit log'],
  ['admin/infrastructure', 'Admin', 'Infrastructure', 'Infrastructure'],
  ...(globalThis.EXTRA_ROUTES ?? []),
]

const root = new URL('..', import.meta.url).pathname
for (const [route, mod, exp, title] of ROUTES) {
  const file = join(root, 'src/pages/portal', route, 'index.astro')
  mkdirSync(dirname(file), { recursive: true })
  const rel = (p) => relative(dirname(file), join(root, p)).replace(/\\/g, '/')
  writeFileSync(
    file,
    `---\n// Generated by scripts/portal-pages.mjs\nimport Portal from '${rel('src/layouts/Portal.astro')}'\nimport { ${exp} } from '${rel(`src/portal/pages/${mod}`)}'\n---\n\n<Portal title="${title}"><${exp} client:only="preact" /></Portal>\n`,
  )
}
console.log(`wrote ${ROUTES.length} portal pages`)
